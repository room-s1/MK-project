// Расстояние между символами (в пикселях)
#define CHAR_SPACING 1

const ST7735_Font Font_5x7 = {.data = font_5x7_data, .width = 5, .height = 7, .first_char = 32, .last_char = 122};

/*
 * Рисование одного символа
 * x, y - координаты левого верхнего угла
 */
void ST7735_DrawChar(ST7735_Handle* handle, uint16_t x, uint16_t y, char ch, const ST7735_Font* font, uint16_t color,
                     uint16_t bg_color)
{
  if (!handle || !font || !font->data) return;

  uint8_t char_code = (uint8_t)ch;
  if (char_code < font->first_char || char_code > font->last_char) return;

  // Смещение в массиве данных для нужного символа
  uint16_t offset = (char_code - font->first_char) * font->width;

  // Рисуем символ по столбцам
  for (uint8_t col = 0; col < font->width; col++)
  {
    uint8_t column = font->data[offset + col];

    for (uint8_t row = 0; row < font->height; row++)
    {
      if (column & (1 << row))
      {
        ST7735_DrawPixel(handle, x + col, y + row, color);
      }
      else if (bg_color != color)
      {
        ST7735_DrawPixel(handle, x + col, y + row, bg_color);
      }
    }
  }
}

/*
 * Рисование строки
 * Поддерживаются символы: '\n' (новая строка), '\r' (возврат каретки)
 */
void ST7735_DrawString(ST7735_Handle* handle, uint16_t x, uint16_t y, const char* str, const ST7735_Font* font,
                       uint16_t color, uint16_t bg_color)
{
  uint16_t current_x = x;

  while (*str)
  {
    if (*str == '\n')
    {
      y += font->height;
      current_x = x;
    }
    else if (*str == '\r')
    {
      current_x = x;
    }
    else if (*str == ' ')
    {
      // Пробел: сдвигаем на ширину символа + отступ
      current_x += font->width + CHAR_SPACING;
    }
    else
    {
      ST7735_DrawChar(handle, current_x, y, *str, font, color, bg_color);
      // После символа добавляем отступ
      current_x += font->width + CHAR_SPACING;
    }
    str++;

    // Перенос строки, если текст выходит за правый край
    if (current_x + font->width > ST7735_WIDTH)
    {
      current_x = x;
      y += font->height;
    }
    if (y + font->height > ST7735_HEIGHT) break;
  }
}

/*
 * Рисование строки по центру экрана (по горизонтали)
 */
void ST7735_DrawStringCenter(ST7735_Handle* handle, uint16_t y, const char* str, const ST7735_Font* font,
                             uint16_t color, uint16_t bg_color)
{
  uint16_t string_width = strlen(str) * (font->width + CHAR_SPACING);
  // Убираем лишний отступ после последнего символа
  if (string_width > 0) string_width -= CHAR_SPACING;

  uint16_t x = (ST7735_WIDTH - string_width) / 2;
  ST7735_DrawString(handle, x, y, str, font, color, bg_color);
}